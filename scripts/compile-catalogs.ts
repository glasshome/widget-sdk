#!/usr/bin/env bun
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { compileCatalogSource, pseudoCatalog } from "@glasshome/widget-contract/catalog-build";
import type { CompiledCatalog } from "@glasshome/widget-contract/i18n-format";

const LOCALES = fileURLToPath(new URL("../src/locales", import.meta.url));
const COMPILED = join(LOCALES, "compiled");
const PSEUDO = "en-XA";
const SOURCE = /^([a-z]{2})\.json$/u;

function compileSdkCatalogs(): Record<string, CompiledCatalog> {
  const out: Record<string, CompiledCatalog> = {};
  for (const name of readdirSync(LOCALES).sort()) {
    const language = SOURCE.exec(name)?.[1];
    if (!language) continue;
    const file = join(LOCALES, name);
    out[language] = compileCatalogSource(readFileSync(file, "utf-8"), file);
  }
  const en = out.en;
  if (!en) throw new Error(`${LOCALES}: no en.json`);
  out[PSEUDO] = pseudoCatalog(en);
  return out;
}

function moduleSource(language: string, catalog: CompiledCatalog): string {
  const body = JSON.stringify(catalog, null, 2);
  const head = `// Generated by \`bun run catalogs\` from ${language === PSEUDO ? "en" : language}.json; do not edit.\nimport type { CompiledCatalog } from "@glasshome/widget-contract/i18n-format";\n\n`;
  return language === "en"
    ? `${head}const catalog = ${body} satisfies CompiledCatalog;\n\nexport type SdkKey = keyof typeof catalog;\nexport default catalog;\n`
    : `${head}const catalog: CompiledCatalog = ${body};\n\nexport default catalog;\n`;
}

if (import.meta.main) {
  mkdirSync(COMPILED, { recursive: true });
  const files = Object.entries(compileSdkCatalogs()).map(([language, catalog]) => {
    const file = join(COMPILED, `${language}.ts`);
    writeFileSync(file, moduleSource(language, catalog));
    return file;
  });
  const fmt = Bun.spawnSync(["oxfmt", ...files], { stdio: ["inherit", "inherit", "inherit"] });
  if (fmt.exitCode !== 0) process.exit(fmt.exitCode ?? 1);
  console.log(`catalogs: ${files.length} modules in ${COMPILED}`);
}
